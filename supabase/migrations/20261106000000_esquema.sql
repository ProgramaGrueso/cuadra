create function public.prestadores_cercanos(
  p_lat double precision,
  p_lng double precision,
  p_radio_m integer default 2000,
  p_oficio_id smallint default null,
  p_solo_emergencia boolean default false
) returns table (
  id uuid, nombre text, oficio_id smallint, oficio text, icono text,
  descripcion text, tarifa_ref text, disponible_emergencia boolean,
  lat double precision, lng double precision, distancia_m integer,
  vistos_buenos integer, sello boolean, favores_hechos integer, tiene_whatsapp boolean
)
language sql stable security definer set search_path = public, extensions, pg_temp as $$
  with punto as (
    select st_setsrid(st_makepoint(p_lng, p_lat), 4326)::geography as g
  )
  select
    p.id, u.nombre, o.id, o.nombre, o.icono, p.descripcion, p.tarifa_ref, p.disponible_emergencia,
    p.lat, p.lng, round(st_distance(p.geom, punto.g))::integer,
    coalesce(v.total, 0)::integer, coalesce(v.total, 0) >= 3,
    pp.favores_hechos, u.telefono is not null
  from public.prestadores p
  cross join punto
  join public.users u on u.id = p.user_id
  join public.oficios o on o.id = p.oficio_id
  join public.perfiles_publicos pp on pp.id = p.user_id
  left join lateral (
    select count(*) as total from public.vistos_buenos vb where vb.prestador_id = p.id
  ) v on true
  where auth.uid() is not null
    and st_dwithin(p.geom, punto.g, least(greatest(p_radio_m, 100), 10000))
    and (p_oficio_id is null or p.oficio_id = p_oficio_id)
    and (not p_solo_emergencia or (p.disponible_emergencia and o.es_critico_emergencia))
  order by coalesce(v.total, 0) desc, st_distance(p.geom, punto.g) asc
  limit 200
$$;

