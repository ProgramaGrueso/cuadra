-- Quien toma el favor pasa a en_curso. Solo uno gana aunque toquen a la vez.
create function public.tomar_favor(p_favor_id uuid) returns public.favores
language plpgsql security definer set search_path = '' as $$
declare v public.favores;
begin
  update public.favores set estado = 'en_curso', ayudante_id = auth.uid()
    where id = p_favor_id and estado = 'abierto' and autor_id <> auth.uid() and auth.uid() is not null
    returning * into v;
  if v.id is null then
    raise exception 'Este favor ya no esta disponible' using errcode = 'P0001';
  end if;
  return v;
end $$;

-- Lo confirma quien recibio el favor: asi el contador no se puede inflar solo.
create function public.cumplir_favor(p_favor_id uuid) returns public.favores
language plpgsql security definer set search_path = '' as $$
declare v public.favores;
begin
  update public.favores set estado = 'cumplido'
    where id = p_favor_id and estado = 'en_curso'
      and ((tipo = 'pido' and autor_id = auth.uid())
        or (tipo = 'ofrezco' and ayudante_id = auth.uid()))
    returning * into v;
  if v.id is null then
    raise exception 'Solo quien recibio el favor puede confirmarlo' using errcode = 'P0001';
  end if;
  return v;
end $$;

-- Un simulacro precargado se reutiliza, asi cada ensayo arranca con su escenario.
create function public.activar_emergencia(p_zona_id smallint, p_mensaje text default null)
returns public.emergencias
language plpgsql security definer set search_path = '' as $$
declare v public.emergencias;
begin
  if not public.puede_coordinar() then
    raise exception 'Solo un vecino verificado puede activar la emergencia' using errcode = '42501';
  end if;
  select * into v from public.emergencias where zona_id = p_zona_id and activa;
  if v.id is not null then
    return v;
  end if;
  update public.emergencias
    set activa = true, activada_por = auth.uid(), finalizada_en = null,
        mensaje = coalesce(p_mensaje, mensaje)
    where zona_id = p_zona_id and es_simulacro
    returning * into v;
  if v.id is null then
    insert into public.emergencias (zona_id, activa, activada_por, mensaje)
      values (p_zona_id, true, auth.uid(), coalesce(p_mensaje, 'Emergencia activa en tu zona'))
      returning * into v;
  end if;
  return v;
end $$;

create function public.desactivar_emergencia(p_emergencia_id uuid) returns public.emergencias
language plpgsql security definer set search_path = '' as $$
declare v public.emergencias;
begin
  if not public.puede_coordinar() then
    raise exception 'Solo un vecino verificado puede desactivar la emergencia' using errcode = '42501';
  end if;
  update public.emergencias set activa = false, finalizada_en = now()
    where id = p_emergencia_id returning * into v;
  return v;
end $$;

-- Idempotente: la cola offline puede reintentarlo con el mismo id.
create function public.crear_reporte(
  p_id uuid, p_emergencia_id uuid, p_tipo text, p_descripcion text,
  p_lat double precision, p_lng double precision, p_direccion text
) returns uuid
language plpgsql security definer set search_path = '' as $$
begin
  if auth.uid() is null then
    raise exception 'Sesion requerida' using errcode = '42501';
  end if;
  insert into public.reportes_vulnerables
    (id, emergencia_id, tipo, descripcion, lat_aprox, lng_aprox, reportado_por)
    values (p_id, p_emergencia_id, p_tipo, p_descripcion, p_lat, p_lng, auth.uid())
    on conflict (id) do nothing;
  if found then
    insert into public.reportes_direcciones (reporte_id, direccion) values (p_id, p_direccion);
  end if;
  return p_id;
end $$;

-- Con registro anonimo, entregar la direccion a cualquiera anularia la privacidad:
-- solo un voluntario verificado puede aceptar y recibirla.
create function public.atender_reporte(p_reporte_id uuid) returns text
language plpgsql security definer set search_path = '' as $$
declare v_id uuid; v_direccion text;
begin
  if not public.puede_coordinar() then
    raise exception 'Solo un voluntario verificado puede aceptar reportes' using errcode = '42501';
  end if;
  update public.reportes_vulnerables set estado = 'en_atencion', atendido_por = auth.uid()
    where id = p_reporte_id and estado = 'pendiente' returning id into v_id;
  if v_id is null then
    raise exception 'Este reporte ya fue tomado por otro voluntario' using errcode = 'P0001';
  end if;
  select direccion into v_direccion from public.reportes_direcciones where reporte_id = v_id;
  return v_direccion;
end $$;

create function public.cerrar_reporte(p_reporte_id uuid) returns void
language plpgsql security definer set search_path = '' as $$
begin
  update public.reportes_vulnerables set estado = 'atendido'
    where id = p_reporte_id and estado = 'en_atencion'
      and (atendido_por = auth.uid() or public.es_admin());
  if not found then
    raise exception 'Solo el voluntario asignado puede cerrar este reporte' using errcode = 'P0001';
  end if;
end $$;

create function public.conteo_checkins(p_emergencia_id uuid) returns integer
language sql stable security definer set search_path = '' as $$
  select count(*)::integer from public.checkins
  where emergencia_id = p_emergencia_id and estado = 'bien' and auth.uid() is not null
$$;

