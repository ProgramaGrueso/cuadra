-- ------------------------------------------------------- redondeo de ubicacion
create function public.redondear_lat_lng() returns trigger
language plpgsql set search_path = '' as $$
begin
  new.lat := round(new.lat::numeric, 3)::double precision;
  new.lng := round(new.lng::numeric, 3)::double precision;
  return new;
end $$;

create function public.redondear_lat_lng_aprox() returns trigger
language plpgsql set search_path = '' as $$
begin
  new.lat_aprox := round(new.lat_aprox::numeric, 3)::double precision;
  new.lng_aprox := round(new.lng_aprox::numeric, 3)::double precision;
  return new;
end $$;

