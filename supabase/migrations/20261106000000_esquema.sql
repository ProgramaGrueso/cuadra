create view public.perfiles_publicos as
  select
    u.id,
    u.nombre,
    u.verificado,
    (select count(*) from public.favores f
      where f.estado = 'cumplido'
        and ((f.tipo = 'pido' and f.ayudante_id = u.id)
          or (f.tipo = 'ofrezco' and f.autor_id = u.id)))::integer as favores_hechos
  from public.users u;

