-- Cuadra: esquema base, RLS y RPC.
--
-- Decisiones de privacidad (son parte del pitch):
--  * RLS filtra filas, no columnas: la direccion exacta de un reporte vive en
--    reportes_direcciones, nunca en reportes_vulnerables.
--  * users guarda telefono y ubicacion exacta: solo el dueno lee su fila. Los
--    demas ven perfiles_publicos y piden el telefono por RPC.
--  * Toda ubicacion publica se redondea a ~110 m en la base, no en el cliente.
--  * Nada se escribe directo si cambia un estado: las transiciones son RPC.

create extension if not exists postgis with schema extensions;

